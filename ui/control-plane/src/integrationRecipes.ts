// Application-oriented examples are intentionally distinct from Exact Replay.
// They use official SDKs and demonstrate response consumption, but may not
// produce byte-identical HTTP requests; request.json remains the authority.
export const PYTHON_SDK_RECIPE = [
  '"""Example application integration: pip install openai."""',
  'import json',
  'import os',
  'from pathlib import Path',
  'from openai import APIError, OpenAI',
  '',
  'body = json.loads(Path(__file__).with_name("request.json").read_text(encoding="utf-8"))',
  '# OpenAI SDK keyword arguments and provider extensions have different contracts.',
  'standard = {',
  '    "model", "messages", "stream", "stream_options", "temperature", "top_p",',
  '    "max_tokens", "max_completion_tokens", "n", "stop", "presence_penalty",',
  '    "frequency_penalty", "seed", "logit_bias", "logprobs", "top_logprobs",',
  '    "tools", "tool_choice", "parallel_tool_calls", "response_format",',
  '    "user", "store", "metadata", "modalities", "audio", "prediction",',
  '}',
  'kwargs = {key: value for key, value in body.items() if key in standard}',
  'extras = {key: value for key, value in body.items() if key not in standard}',
  'if extras:',
  '    kwargs["extra_body"] = extras',
  'client = OpenAI(',
  '    base_url=os.environ.get("GATEWAY_URL", "http://127.0.0.1:9400").rstrip("/") + "/v1",',
  '    api_key=os.environ.get("API_KEY") or "local-open",',
  ')',
  'try:',
  '    result = client.chat.completions.create(**kwargs)',
  '    if body.get("stream") is True:',
  '        pending_tools = {}  # indexed fragments, never execute blindly',
  '        for event in result:',
  '            for choice in event.choices:',
  '                delta = choice.delta',
  '                if delta.content:',
  '                    print(delta.content, end="", flush=True)',
  '                for call in delta.tool_calls or []:',
  '                    item = pending_tools.setdefault(call.index, {"id": "", "name": "", "arguments": ""})',
  '                    if call.id:',
  '                        item["id"] = call.id',
  '                    if call.function and call.function.name:',
  '                        item["name"] += call.function.name',
  '                    if call.function and call.function.arguments:',
  '                        item["arguments"] += call.function.arguments',
  '        print()',
  '        if pending_tools:',
  '            print("Pending tool requests (not executed):", json.dumps(pending_tools, ensure_ascii=False))',
  '    else:',
  '        print(result.model_dump_json(indent=2))',
  '        for choice in result.choices:',
  '            message = choice.message',
  '            if message.tool_calls:',
  '                print("Tool calls require validated application execution and a follow-up request.")',
  '            if message.content and body.get("response_format", {}).get("type") in ("json_object", "json_schema"):',
  '                parsed = json.loads(message.content)',
  '                print("Parsed structured result:", parsed)',
  'except APIError as error:',
  '    print("Gateway API error:", getattr(error, "status_code", None), error)',
  '    raise SystemExit(1) from error',
  '',
].join('\n');

export const JAVASCRIPT_SDK_RECIPE = [
  '// Example application integration: npm install openai (Node.js 18+).',
  "import OpenAI from 'openai';",
  "import { readFile } from 'node:fs/promises';",
  "const body = JSON.parse(await readFile(new URL('./request.json', import.meta.url), 'utf8'));",
  'const client = new OpenAI({',
  "  baseURL: (process.env.GATEWAY_URL ?? 'http://127.0.0.1:9400').replace(/\\/$/, '') + '/v1',",
  "  apiKey: process.env.API_KEY || 'local-open',",
  '});',
  'try {',
  '  const result = await client.chat.completions.create(body);',
  '  if (body.stream === true) {',
  '    const pendingTools = new Map();',
  '    for await (const event of result) {',
  '      for (const choice of event.choices ?? []) {',
  "        if (choice.delta?.content) process.stdout.write(choice.delta.content);",
  '        // Aggregate fragments by tool index; execution must be explicitly authorized.',
  '        for (const call of choice.delta?.tool_calls ?? []) {',
  '          const current = pendingTools.get(call.index) ?? { id: "", name: "", arguments: "" };',
  '          if (call.id) current.id = call.id;',
  '          if (call.function?.name) current.name += call.function.name;',
  '          if (call.function?.arguments) current.arguments += call.function.arguments;',
  '          pendingTools.set(call.index, current);',
  '        }',
  '      }',
  '    }',
  "    process.stdout.write('\\n');",
  '    if (pendingTools.size) console.error("Pending tool requests (not executed):", [...pendingTools.values()]);',
  '  } else {',
  '    console.log(JSON.stringify(result, null, 2));',
  '    for (const choice of result.choices ?? []) {',
  '      if (choice.message?.tool_calls?.length) console.error("Tool calls need validation and a follow-up request.");',
  '      if (choice.message?.content && ["json_object", "json_schema"].includes(body.response_format?.type)) {',
  '        console.log("Parsed structured result:", JSON.parse(choice.message.content));',
  '      }',
  '    }',
  '  }',
  '} catch (error) {',
  '  console.error("Gateway SDK request failed:", error.status ?? error.code ?? "", error.message);',
  '  process.exitCode = 1;',
  '}',
  '',
].join('\n');
